#!/usr/bin/env python3
"""Build a reproducible 100-row external human-label calibration manifest."""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Callable


DATASET_ID = "mteb/summeval"
DATASET_REVISION = "bfc121155064afa2d81b5505682ffc0d96f4334c"
DATASET_CONFIG = "default"
DATASET_SPLIT = "test"
DEFAULT_OUTPUT = Path(__file__).with_name("external-human-labels-summeval-v1.jsonl")


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def load_pinned_rows() -> list[dict[str, Any]]:
    """Load the declared immutable dataset revision, never upstream main."""
    from datasets import load_dataset

    dataset = load_dataset(
        DATASET_ID,
        DATASET_CONFIG,
        split=DATASET_SPLIT,
        revision=DATASET_REVISION,
    )
    rows = [
        {"row_idx": index, "row": dict(row)}
        for index, row in enumerate(dataset)
    ]
    if len(rows) != 100:
        raise RuntimeError(
            "expected the pinned SummEval test split to contain 100 rows"
        )
    return rows


def _select_one_per_document(
    rows: list[dict[str, Any]],
    predicate: Callable[[float], bool],
    count: int,
) -> list[dict[str, Any]]:
    candidates: dict[int, list[dict[str, Any]]] = defaultdict(list)
    for item in rows:
        row_idx = int(item["row_idx"])
        row = item["row"]
        for summary_index, (summary, score) in enumerate(
            zip(row["machine_summaries"], row["consistency"], strict=True)
        ):
            score = float(score)
            if predicate(score):
                candidates[row_idx].append(
                    {
                        "row_idx": row_idx,
                        "document_id": row["id"],
                        "summary_index": summary_index,
                        "expert_consistency_score": score,
                        "source_sha256": _sha256(row["text"]),
                        "summary_sha256": _sha256(summary),
                    }
                )

    selected: list[dict[str, Any]] = []
    for row_idx in sorted(candidates):
        if len(selected) == count:
            break
        if candidates[row_idx]:
            selected.append(candidates[row_idx][0])
    if len(selected) != count:
        raise RuntimeError(f"needed {count} distinct documents, found {len(selected)}")
    return selected


def build_manifest() -> list[dict[str, Any]]:
    rows = load_pinned_rows()

    negative = _select_one_per_document(rows, lambda score: score <= 2.0, 50)
    positive = _select_one_per_document(rows, lambda score: score >= 4.0, 50)
    records: list[dict[str, Any]] = []
    for index, item in enumerate(negative + positive, 1):
        human_pass = item["expert_consistency_score"] >= 4.0
        records.append(
            {
                "schema_version": "m14-summeval-human-label-v1",
                "case_id": f"M14-EXT-SE-{index:03d}",
                "dataset_id": DATASET_ID,
                "dataset_revision": DATASET_REVISION,
                "dataset_config": DATASET_CONFIG,
                "dataset_split": DATASET_SPLIT,
                **item,
                "human_pass": human_pass,
                "label_source": "mean_of_three_independent_SummEval_expert_consistency_scores",
                "label_rule": "pass_if_expert_consistency_gte_4_of_5_fail_if_lte_2_of_5",
            }
        )
    return records


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="compare generated bytes to output")
    args = parser.parse_args()

    rendered = "".join(
        json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "\n"
        for record in build_manifest()
    )
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != rendered:
            print(f"STALE: {args.output}")
            return 2
        print(f"PASS: {args.output} is reproducible (100 external human labels)")
        return 0

    args.output.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Wrote {args.output}: 50 low-consistency + 50 high-consistency expert labels")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
